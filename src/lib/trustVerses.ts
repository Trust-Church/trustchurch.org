  TRUST_VERSES.find(
    (verse) => verse.id === "jeremiah-17-7-8"
  ) ?? TRUST_VERSES[0];

export function getRandomTrustVerse(): TrustVerse {
  return TRUST_VERSES[
    Math.floor(Math.random() * TRUST_VERSES.length)
  ];
}

export function getTrustVerseById(
  id: string
): TrustVerse | undefined {
  return TRUST_VERSES.find(
    (verse) => verse.id === id
  );
}